#!/usr/bin/env node
/**
 * Selects which client profile (clients/<id>.ts) this build uses.
 *
 *   npm run use-client -- maya-patel-coaching   switch + validate
 *   npm run use-client -- --list                list available clients
 *   node scripts/use-client.mjs --from-env      (prebuild) switch to $CLIENT_ID if set
 *
 * Writes src/config/active-client.ts, which imports exactly one client file,
 * so no other client's details end up in the built app.
 */
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const clientsDir = path.join(root, 'clients');
const activeFile = path.join(root, 'src', 'config', 'active-client.ts');

const args = process.argv.slice(2);
const listClients = () =>
  fs
    .readdirSync(clientsDir)
    .filter((f) => f.endsWith('.ts') && !f.startsWith('_'))
    .map((f) => f.replace(/\.ts$/, ''))
    .sort();

const currentActive = () => {
  const m = fs.readFileSync(activeFile, 'utf8').match(/clients\/([a-z0-9-]+)'/);
  return m ? m[1] : null;
};

function fail(message) {
  console.error(`\n✖ ${message}\n`);
  process.exit(1);
}

if (args.includes('--list')) {
  const active = currentActive();
  for (const id of listClients()) console.log(`${id === active ? '●' : ' '} ${id}`);
  process.exit(0);
}

let id = args.find((a) => !a.startsWith('--'));
if (args.includes('--from-env')) {
  id = (process.env.CLIENT_ID || '').trim();
  if (!id) {
    console.log(`[use-client] CLIENT_ID not set — building active client "${currentActive()}".`);
    process.exit(0);
  }
}
if (!id) fail('Usage: npm run use-client -- <client-id>   (or --list)');

const file = path.join(clientsDir, `${id}.ts`);
if (!fs.existsSync(file)) {
  fail(`clients/${id}.ts not found. Available: ${listClients().join(', ') || '(none)'}`);
}
const source = fs.readFileSync(file, 'utf8');
const declaredId = source.match(/\bid:\s*'([^']+)'/)?.[1];
if (declaredId !== id) fail(`clients/${id}.ts declares id '${declaredId}'. It must match the file name.`);
if (/REPLACE/.test(source)) {
  const lines = source
    .split('\n')
    .map((l, i) => (/REPLACE/.test(l) ? `  line ${i + 1}: ${l.trim()}` : null))
    .filter(Boolean);
  fail(`clients/${id}.ts still has template placeholders:\n${lines.join('\n')}`);
}

const previous = fs.readFileSync(activeFile, 'utf8');
fs.writeFileSync(
  activeFile,
  `// AUTO-GENERATED by scripts/use-client.mjs — do not edit by hand.\n// Switch clients with: npm run use-client -- <client-id>\nexport { default } from '../../clients/${id}';\n`
);

if (!args.includes('--no-check')) {
  const check = spawnSync('npx', ['vitest', 'run', 'tests/client-config.test.ts'], {
    cwd: root,
    stdio: 'inherit',
    env: { ...process.env, CHECK_CLIENT_ID: id },
  });
  if (check.status !== 0) {
    fs.writeFileSync(activeFile, previous);
    fail(`clients/${id}.ts failed validation (see above). Active client left unchanged.`);
  }
}

console.log(`\n✔ Active client: ${id}\n`);
